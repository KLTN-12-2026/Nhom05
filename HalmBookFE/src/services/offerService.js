import axios from './axiosClient.js';
const notify = () => { if (typeof window !== 'undefined') window.dispatchEvent(new Event('halm-offers-updated')); };
const list = (kind, admin) => axios.get(admin ? '/api/admin/book-offers' : '/api/home/book-offers', { params: { kind } }).then(r => r.data);
const save = async (kind, id, data) => { const body = { ...data, kind }; const result = await (id ? axios.put('/api/admin/book-offers/' + encodeURIComponent(id), body) : axios.post('/api/admin/book-offers', body)); notify(); return result.data; };
const remove = async id => { const result = await axios.delete('/api/admin/book-offers/' + encodeURIComponent(id)); notify(); return result.data; };
export const getCombos = (admin = false) => list('COMBO', admin);
export const getSingleDeals = (admin = false) => list('SINGLE', admin);
export const addCombo = data => save('COMBO', null, data);
export const updateCombo = (id, data) => save('COMBO', id, data);
export const deleteCombo = remove;
export const addSingleDeal = data => save('SINGLE', null, data);
export const updateSingleDeal = (id, data) => save('SINGLE', id, data);
export const deleteSingleDeal = remove;
export const addOfferToCart = id => axios.post('/api/home/cart/offers/' + encodeURIComponent(id)).then(r => r.data);
export const applyCartCoupon = (couponCode, bookId, planKey) => axios.post('/api/home/cart/coupon', { couponCode, bookId, planKey }).then(r => r.data);
export const clearCartCoupon = () => axios.delete('/api/home/cart/coupon').then(r => r.data);
export const getCartQuote = cartItemIds => axios.post('/api/home/checkout/quote', { cartItemIds }).then(r => r.data);
